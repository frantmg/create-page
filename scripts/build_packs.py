#!/usr/bin/env python3
"""Build one reading pack per agent role: the exact text of the files that role must read, in one file.
Usage: python3 build_packs.py            (writes <kit>/agents/packs/<role>.md)
       python3 build_packs.py --check    (exit 1 if a pack is missing or out of date)

An agent then reads everything it needs in a single step instead of opening 4 to 6 files one by one. The packs
contain the rule files word for word (nothing is shortened or summarised), each under a header with its path.
Run it whenever a rule file or agents/shared.md changes, and before every release (START-HERE.md section 9)."""
import hashlib, pathlib, sys

KIT = pathlib.Path(__file__).resolve().parent.parent
PACKS = {
    "content":  ["agents/shared.md", "rules/materials.md", "rules/blocks-and-plan.md", "rules/copy.md"],
    "designer": ["agents/shared.md", "rules/materials.md", "rules/design-build.md", "rules/qa.md", "rules/copy.md"],
    "qa":       ["agents/shared.md", "rules/qa.md", "rules/copy.md", "rules/design-build.md", "rules/blocks-and-plan.md", "rules/materials.md"],
}
version = (KIT / "VERSION").read_text().strip()

def build(role, files):
    body = "".join(f"\n\n<!-- ===== {f} ===== -->\n\n" + (KIT / f).read_text(encoding="utf-8").strip() + "\n" for f in files)
    digest = hashlib.sha1(body.encode()).hexdigest()[:12]
    head = (f"# Reading pack: {role} (kit v{version}, sources {digest})\n\n"
            f"Generated by scripts/build_packs.py from: {', '.join(files)}. The text below is those files word for word; "
            "if anything here differs from the files, the files win.\n")
    return head + body, digest

stale = []
for role, files in PACKS.items():
    text, digest = build(role, files)
    out = KIT / "agents" / "packs" / f"{role}.md"
    if "--check" in sys.argv:
        if not out.exists() or f"sources {digest}" not in out.read_text(encoding="utf-8").splitlines()[0] or f"kit v{version}" not in out.read_text(encoding="utf-8").splitlines()[0]:
            stale.append(role)
    else:
        out.parent.mkdir(parents=True, exist_ok=True); out.write_text(text, encoding="utf-8")
        print(f"{out.relative_to(KIT)}  {len(text.encode()) // 1024} KB  ({len(files)} files)")
if "--check" in sys.argv:
    print("packs up to date" if not stale else f"stale packs: {', '.join(stale)} (run scripts/build_packs.py)")
    sys.exit(1 if stale else 0)
